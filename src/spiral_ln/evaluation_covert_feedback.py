"""Exact finite risk from bounded *unrecorded* information after public feedback.

The attacker may compute a covert symbol as an arbitrary function of the full
null world and the public transcript, then select one false-positive event
using only that symbol and transcript. The number of covert symbols per
public transcript is bounded by \`messages\`. This is an *adversarial upper
bound* under that explicit alphabet assumption, not evidence that an actor's
actual information flow has such a bound.

The resulting optimization is weighted maximum coverage. All arithmetic is
integer or fractions.Fraction, and the independent verifier enumerates covert
label assignments rather than importing the coverage construction.
"""
from __future__ import annotations

from fractions import Fraction
from itertools import combinations, product
from math import prod

from spiral_ln.evaluation_selection_risk import (
    NullModel, QueryNode, full_information_risk, no_feedback_risk,
    policy_fibres, risk_for_fibres,
)


def validate_fibres(model: NullModel, fibres=None) -> tuple[tuple[int, ...], ...]:
    """Ensure the public observation classes partition all positive-mass worlds."""
    if fibres is None:
        return (tuple(range(len(model.weights))),)
    groups = tuple(tuple(indices) for indices in fibres)
    if (not groups or any(not group for group in groups)
            or any(type(i) is not int or not 0 <= i < len(model.weights)
                   for group in groups for i in group)
            or sorted(i for group in groups for i in group)
            != list(range(len(model.weights)))):
        raise ValueError("public fibres must be a partition of all null worlds")
    return groups


def covered_mass(model: NullModel, worlds: tuple[int, ...], selected: tuple[int, ...]) -> int:
    """Mass where at least one selected false-positive event fires."""
    return sum(model.weights[i] for i in worlds
               if any(model.events[j][i] for j in selected))


def best_event_cover(model: NullModel, worlds: tuple[int, ...], messages: int):
    """Exact maximum-coverage set of at most \`messages\` possible test choices.

    Ties are resolved by increasing lexicographic order. Nonnegative masses
    imply that exactly min(messages, number of tests) distinct choices suffice.
    """
    if type(messages) is not int or messages < 1:
        raise ValueError("messages must be a positive integer")
    if not worlds:
        raise ValueError("each public fibre must be nonempty")
    if any(type(i) is not int or i < 0 or i >= len(model.weights) for i in worlds):
        raise ValueError("invalid world index")
    event_count = len(model.events)
    best_mass = -1
    best_selected = ()
    for selected in combinations(range(event_count), min(messages, event_count)):
        mass = covered_mass(model, worlds, selected)
        if mass > best_mass:
            best_mass, best_selected = mass, selected
    return best_mass, best_selected


def covert_risk(model: NullModel, messages: int, fibres=None) -> dict:
    """Worst-case probability of one false authorization after public + covert info.

    Public \`fibres\` can be generated by a sequential adaptive query policy.
    For each public transcript, the covert reporter has at most \`messages\`
    symbols. It can inspect the full null world before choosing its symbol.
    The selected test depends only on the public transcript and that symbol.
    """
    public = validate_fibres(model, fibres)
    if type(messages) is not int or messages < 1:
        raise ValueError("messages must be a positive integer")
    selected = tuple(best_event_cover(model, group, messages) for group in public)
    mass = sum(row[0] for row in selected)
    base = risk_for_fibres(model, public)
    upper = full_information_risk(model)
    result = Fraction(mass, model.total)
    assert base <= result <= min(upper, messages * base)
    return {
        "risk": result, "public_risk": base, "full_information_risk": upper,
        "extra_risk": result - base, "messages": messages,
        "public_fibres": public,
        "selected_event_sets": tuple(choice for _, choice in selected),
        "covered_mass": mass,
    }


def covert_tree_risk(model: NullModel, public_policy: QueryNode, messages: int) -> dict:
    """Apply the oracle to every reachable leaf of a recorded query tree."""
    return covert_risk(model, messages, policy_fibres(model, public_policy).values())


def covert_witness_labels(model: NullModel, messages: int, fibres=None):
    """Construct optimal covert labels and chosen tests for each public fibre.

    For every world, the label points to the first winning event if any, and
    defaults to zero otherwise. The selected test for each possible symbol
    is the corresponding element of the maximum-cover set.
    """
    report = covert_risk(model, messages, fibres)
    assignments = []
    for group, events in zip(report["public_fibres"], report["selected_event_sets"]):
        labels = tuple(next((label for label, j in enumerate(events)
                             if model.events[j][i]), 0) for i in group)
        assignments.append(tuple(zip(group, labels)))
    assert sum(sum(model.weights[i] for i, label in labels
                   if model.events[events[label]][i])
               for events, labels in zip(report["selected_event_sets"], assignments)) == report["covered_mass"]
    return {**report, "covert_world_labels": tuple(assignments)}


def independent_boolean_null(test_count: int, denominator: int = 20) -> NullModel:
    """IID Bernoulli(1/denominator) false-positive events, exact integer masses.

    Queries include a constant channel and the bit for each test event, so
    public per-test feedback can be studied separately from covert messages.
    """
    if (type(test_count) is not int or not 1 <= test_count <= 10
            or type(denominator) is not int or denominator < 2):
        raise ValueError("positive test_count <=10 and integer denominator>=2 required")
    atoms = tuple(product((0, 1), repeat=test_count))
    weights = tuple(prod(1 if bit else denominator - 1 for bit in atom)
                    for atom in atoms)
    events = tuple(tuple(bool(atom[j]) for atom in atoms)
                   for j in range(test_count))
    queries = ((0,) * len(atoms),) + tuple(
        tuple(atom[j] for atom in atoms) for j in range(test_count))
    return NullModel(weights, events, queries)


def brute_force_covert_risk(model: NullModel, messages: int, fibres=None) -> Fraction:
    """Independent small-state oracle enumerating covert code assignments.

    Enumerates every function hidden:world->message within each public fibre.
    At each observed message, independently picks the best event. Unlike
    covert_risk, this implementation never enumerates subsets of event IDs.
    Exponential in number of worlds; use only in short deterministic checks.
    """
    public = validate_fibres(model, fibres)
    if type(messages) is not int or messages < 1:
        raise ValueError("messages must be positive")
    total = 0
    for group in public:
        if len(group) > 8 or messages > 3:
            raise ValueError("independent oracle limited to <=8 worlds and <=3 messages per fibre")
        best = 0
        for assignment in product(range(messages), repeat=len(group)):
            sum_by_message = 0
            for symbol in range(messages):
                chosen_worlds = tuple(i for i, h in zip(group, assignment) if h == symbol)
                if chosen_worlds:
                    sum_by_message += max(sum(model.weights[i] for i in chosen_worlds
                                              if event[i]) for event in model.events)
            if sum_by_message > best:
                best = sum_by_message
        total += best
    return Fraction(total, model.total)


def minimum_full_exposure_messages(model: NullModel, fibres=None) -> dict:
    """Smallest covert alphabet giving full selection risk in every public leaf.

    This is an exact finite set-cover problem on the positive-mass worlds
    where at least one false-positive event occurs. A different event subset
    may be chosen for each public response. Returns the maximum leaf budget.
    """
    public = validate_fibres(model, fibres)
    thresholds = []
    covers = []
    for group in public:
        target = covered_mass(model, group, tuple(range(len(model.events))))
        for count in range(1, len(model.events) + 1):
            mass, chosen = best_event_cover(model, group, count)
            if mass == target:
                thresholds.append(count)
                covers.append(chosen)
                break
        else:
            raise AssertionError("full event union must be coverable")
    budget = max(thresholds)
    assert covert_risk(model, budget, public)["risk"] == full_information_risk(model)
    return {"messages": budget, "per_public_leaf": tuple(thresholds),
            "covering_event_sets": tuple(covers)}
