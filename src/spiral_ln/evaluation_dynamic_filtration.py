"""Exact finite validity of a public e-process under an actor's richer filtration.

Four exact finite constructions, all in ``fractions.Fraction``:

A. Private stopping of a public nonnegative supermartingale. ``PrivateSignalLaw`` is a joint
   law of a public symbol path g_1..g_n and one private symbol h (known to the actor from time
   zero: the worst acquisition time). ``worst_stopped_expectation`` is the exact supremum of
   E[M_tau] over stopping times of the enlarged filtration for a given public process M;
   ``private_stopping_value`` is its supremum over every nonnegative public martingale with
   M_0 = 1, in closed form; ``leakage_certificate`` is the sum over private symbols of the
   largest conditional probability given a full public transcript (the exponential of the
   maximal leakage of Issa, Wagner and Kamath from the public transcript to the private
   symbol), which bounds the value and is itself at most the private alphabet size.

B. ``ControlModel``: an actor with a finite latent Markov state, clean query kernels, a
   private signal per round, a choice of public query and of stopping. ``actor_value`` is the
   exact supremum of E[E_tau] over all actor policies; two factor families are provided,
   *pointwise* (valid for every latent state) and *calibrated* (valid under the public
   posterior predictive).

C. ``chronology_worst_case``: data-dependent revocation of e-factor sources recorded as a
   VIEW/REVOKE chronology; exact supremum of the reported product over revocation policies
   measurable in the certified (public) filtration.

D. Revocable-provenance audit states: subset posteriors for a static null and subset filters
   for a Markov latent state, with explicit witnesses.

No learner, judge, instrument or real stopping rule is run anywhere in this module.
"""
from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction as Q
from functools import lru_cache
from itertools import product


def _rational(x):
    if type(x) not in (int, Q) or isinstance(x, bool):
        raise ValueError("values must be int or Fraction, never float or bool")
    return Q(x)


def _distribution(row):
    row = tuple(_rational(x) for x in row)
    if not row or any(x < 0 for x in row) or sum(row) != 1:
        raise ValueError("a probability row must be nonempty, nonnegative and sum to one")
    return row


