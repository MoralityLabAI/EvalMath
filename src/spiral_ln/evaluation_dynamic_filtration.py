@dataclass(frozen=True)
class ControlModel:
    """Finite latent Markov chain with clean query kernels and a per-round private signal.

    prior: distribution over latent states. transition[s][s']. kernels[q][s][y]: clean public
    response law of query q in latent state s. private[(s, y_all)]: law of the private symbol
    given the latent state and the vector of *all* pre-drawn responses this round, so a private
    signal may concern the latent state ('latent'), the upcoming evidence ('data'), or both.
    weights[q][y]: a nonnegative row summing to at most one, defining the factor families:
      pointwise:  f_q(y) = weights[q][y] / max_s kernels[q][s][y]   (valid for every s)
      calibrated: f_q(y) = weights[q][y] / P_pub(y | q, public history)  (public-predictive valid)
    """
    prior: tuple
    transition: tuple
    kernels: tuple
    private: dict
    weights: tuple

    def __post_init__(self):
        prior = _distribution(self.prior)
        s_count = len(prior)
        transition = tuple(_distribution(row) for row in self.transition)
        if len(transition) != s_count or any(len(r) != s_count for r in transition):
            raise ValueError("transition must be a square stochastic matrix over the latent states")
        kernels = []
        for q in self.kernels:
            rows = tuple(_distribution(r) for r in q)
            if len(rows) != s_count or any(len(r) != len(rows[0]) for r in rows):
                raise ValueError("each query kernel needs one row per latent state with a fixed alphabet")
            kernels.append(rows)
        if not kernels:
            raise ValueError("at least one query required")
        weights = tuple(tuple(_rational(x) for x in w) for w in self.weights)
        if (len(weights) != len(kernels) or any(len(w) != len(k[0]) for w, k in zip(weights, kernels))
                or any(x < 0 for w in weights for x in w) or any(sum(w) > 1 for w in weights)):
            raise ValueError("weights must be nonnegative rows of total at most one per query")
        private = {}
        ys = list(product(*[range(len(k[0])) for k in kernels]))
        for s in range(s_count):
            for y in ys:
                if (s, y) not in self.private:
                    raise ValueError("private kernel must cover every (state, response vector)")
                private[(s, y)] = _distribution(self.private[(s, y)])
        lengths = {len(v) for v in private.values()}
        if len(lengths) != 1:
            raise ValueError("private kernel must have a single alphabet")
        object.__setattr__(self, "prior", prior)
        object.__setattr__(self, "transition", transition)
        object.__setattr__(self, "kernels", tuple(kernels))
        object.__setattr__(self, "weights", weights)
        object.__setattr__(self, "private", private)

    @property
    def states(self):
        return len(self.prior)

    @property
    def private_symbols(self):
        return len(next(iter(self.private.values())))

    def response_vectors(self):
        return list(product(*[range(len(k[0])) for k in self.kernels]))

    def pointwise_factor(self, q, y):
        top = max(k[y] for k in self.kernels[q])
        return self.weights[q][y] / top if top else Q(0)

    def calibrated_factor(self, q, y, public_mass):
        total = sum(public_mass)
        predictive = sum(public_mass[s] * self.kernels[q][s][y] for s in range(self.states)) / total
        return self.weights[q][y] / predictive if predictive else Q(0)


def private_kernel(model_states: int, kernels, symbols: int, mode: str, table) -> dict:
    """Build a private kernel of a declared dependence: 'none', 'latent' (table[s]), 'data' (table[y_all]),
    'both' (table[(s, y_all)])."""
    ys = list(product(*[range(len(k[0])) for k in kernels]))
    out = {}
    for s in range(model_states):
        for y in ys:
            if mode == "none":
                out[(s, y)] = tuple(Q(1, symbols) for _ in range(symbols))
            elif mode == "latent":
                out[(s, y)] = tuple(table[s])
            elif mode == "data":
                out[(s, y)] = tuple(table[y])
            elif mode == "both":
                out[(s, y)] = tuple(table[(s, y)])
            else:
                raise ValueError("mode must be none, latent, data or both")
    return out


def actor_value(model: ControlModel, rounds: int, timing: str, family: str):
    """Exact sup over actor policies of E[E_tau], E the product of public factors.

    timing 'before': the private symbol of a round is seen before the actor chooses to stop or
    which query to ask; 'after': the actor commits first, sees the public response, then the
    private symbol. family 'pointwise' or 'calibrated'. State = (actor unnormalised posterior
    over the previous latent state with E folded in, public unnormalised posterior). The chain
    makes one transition before every round, including the first, so S_1 ~ prior * transition.
    The calibrated factor divides by the predictive of the response-only public filter (the
    declared kernels filtered on the recorded responses with the recorded queries taken as
    given), which is the public posterior predictive for every public query policy.
    """
    if timing not in ("before", "after") or family not in ("pointwise", "calibrated"):
        raise ValueError("timing before/after and family pointwise/calibrated")
    if type(rounds) is not int or rounds < 0:
        raise ValueError("rounds must be a nonnegative integer")
    S, L = model.states, model.private_symbols
    ys = model.response_vectors()
    nq = len(model.kernels)

    def factor(q, y, public):
        return model.pointwise_factor(q, y) if family == "pointwise" else model.calibrated_factor(q, y, public)

    def propagate(v):
        return tuple(sum(v[s] * model.transition[s][s2] for s in range(S)) for s2 in range(S))

    def cells_of(mu):
        out = {}
        for s in range(S):
            for y in ys:
                py = Q(1)
                for q in range(nq):
                    py *= model.kernels[q][s][y[q]]
                m = mu[s] * py
                if m:
                    out[(s, y)] = m
        return out

    @lru_cache(None)
    def solve(nu, public, left):
        stop = sum(nu)
        if left == 0 or not stop:
            return stop
        mu, pmu = propagate(nu), propagate(public)
        cells = cells_of(mu)
        if timing == "before":
            total = Q(0)
            for h in range(L):
                hc = {k: m * model.private[k][h] for k, m in cells.items() if model.private[k][h]}
                if not hc:
                    continue
                best = sum(hc.values())
                for q in range(nq):
                    value = Q(0)
                    for yq in range(len(model.kernels[q][0])):
                        fq = factor(q, yq, pmu)
                        nu2 = [Q(0)] * S
                        for (s, y), m in hc.items():
                            if y[q] == yq:
                                nu2[s] += m * fq
                        if any(nu2):
                            pub2 = tuple(pmu[s] * model.kernels[q][s][yq] for s in range(S))
                            value += solve(tuple(nu2), pub2, left - 1)
                    best = max(best, value)
                total += best
            return total
        best = stop
        for q in range(nq):
            value = Q(0)
            for yq in range(len(model.kernels[q][0])):
                fq = factor(q, yq, pmu)
                pub2 = tuple(pmu[s] * model.kernels[q][s][yq] for s in range(S))
                for h in range(L):
                    nu2 = [Q(0)] * S
                    for (s, y), m in cells.items():
                        if y[q] == yq:
                            nu2[s] += m * model.private[(s, y)][h] * fq
                    if any(nu2):
                        value += solve(tuple(nu2), pub2, left - 1)
            best = max(best, value)
        return best

    return solve(model.prior, model.prior, rounds)


def control_leakage_certificate(model: ControlModel, rounds: int) -> Q:
    """sum over private symbol strings of the max over consistent public transcripts of P(h_{1:n} | transcript).

    Public transcript = the sequence of (query, response) pairs; its law is policy-independent
    once the queries are fixed, so the maximum ranges over every query string and response
    string of positive probability. Enumerates full latent paths; tiny models only.
    """
    if type(rounds) is not int or rounds < 0:
        raise ValueError("rounds must be a nonnegative integer")
    S, L, nq = model.states, model.private_symbols, len(model.kernels)
    ys = model.response_vectors()
    best = {}
    for qs in product(range(nq), repeat=rounds):
        # joint mass of (public responses, private string) by forward enumeration
        joint = {}
        def walk(t, mu, pub, priv):
            if t == rounds:
                m = sum(mu)
                if m:
                    joint[(pub, priv)] = joint.get((pub, priv), Q(0)) + m
                return
            mu2 = tuple(sum(mu[s] * model.transition[s][s2] for s in range(S)) for s2 in range(S))
            q = qs[t]
            for y in ys:
                for h in range(L):
                    nu = []
                    for s in range(S):
                        py = Q(1)
                        for qq in range(nq):
                            py *= model.kernels[qq][s][y[qq]]
                        nu.append(mu2[s] * py * model.private[(s, y)][h])
                    if any(nu):
                        walk(t + 1, tuple(nu), pub + (y[q],), priv + (h,))
        walk(0, model.prior, (), ())
        pub_mass = {}
        for (pub, priv), m in joint.items():
            pub_mass[pub] = pub_mass.get(pub, Q(0)) + m
        for (pub, priv), m in joint.items():
            c = m / pub_mass[pub]
            if c > best.get(priv, Q(0)):
                best[priv] = c
    return sum(best.values())


