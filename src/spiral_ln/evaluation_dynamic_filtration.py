# A. Private stopping of a public process
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class PrivateSignalLaw:
    """Joint law of a public path g in prod_t [A_t] and a private symbol h in [L].

    ``mass`` maps (g, h) to a nonnegative rational; zero entries may be omitted. Masses need
    not be normalised. The public filtration G_t is generated by g_1..g_t; the actor's
    filtration is F_t = G_t v sigma(h), with h available from time zero.
    """
    alphabets: tuple[int, ...]
    private_symbols: int
    mass: dict

    def __post_init__(self):
        n = len(self.alphabets)
        if (type(self.private_symbols) is not int or self.private_symbols < 1
                or any(type(a) is not int or a < 1 for a in self.alphabets)):
            raise ValueError("positive private alphabet and per-step public alphabets required")
        clean = {}
        for key, value in self.mass.items():
            g, h = key
            if (len(g) != n or any(type(x) is not int or not 0 <= x < a for x, a in zip(g, self.alphabets))
                    or type(h) is not int or not 0 <= h < self.private_symbols):
                raise ValueError("mass keys must be (public path, private symbol)")
            v = _rational(value)
            if v < 0:
                raise ValueError("masses must be nonnegative")
            if v:
                clean[(tuple(g), h)] = v
        if not clean:
            raise ValueError("the law must have positive total mass")
        object.__setattr__(self, "mass", clean)

    @property
    def horizon(self):
        return len(self.alphabets)

    @property
    def total(self):
        return sum(self.mass.values())

    def public_paths(self):
        return sorted({g for g, _ in self.mass})

    def prefix_mass(self, prefix, h=None):
        t = len(prefix)
        return sum(m for (g, hh), m in self.mass.items()
                   if g[:t] == prefix and (h is None or hh == h))

    def prefixes(self, t):
        return sorted({g[:t] for g in self.public_paths()})

    def children(self, prefix):
        t = len(prefix)
        return sorted({g[:t + 1] for g in self.public_paths() if g[:t] == prefix})

    def conditional(self, prefix, h):
        """P(H = h | G_t = prefix), None when the prefix has zero mass."""
        den = self.prefix_mass(prefix)
        return self.prefix_mass(prefix, h) / den if den else None


def private_stopping_value(law: PrivateSignalLaw) -> Q:
    """sup over nonnegative public martingales M with M_0 = 1 and F-stopping times of E[M_tau].

    Closed form: max over positive-mass public paths g of sum over private symbols h of
    max over t <= n of P(H = h | G_t = g_{<=t}). Proof in the note (extreme points of the
    terminal-density simplex are point masses on public paths).
    """
    best = Q(0)
    for g in law.public_paths():
        value = sum(max(law.conditional(g[:t], h) for t in range(law.horizon + 1))
                    for h in range(law.private_symbols))
        best = max(best, value)
    return best


def leakage_certificate(law: PrivateSignalLaw) -> Q:
    """sum_h max_g P(H = h | G_n = g) over positive-mass full transcripts g.

    Equal to exp of the maximal leakage from the public transcript to the private symbol.
    """
    paths = law.public_paths()
    return sum(max(law.conditional(g, h) for g in paths) for h in range(law.private_symbols))


def total_variation_value(law: PrivateSignalLaw) -> Q:
    """One-step closed form: 1 + max_g TV(P_H, P_{H|G_n = g}); equals the value when n = 1."""
    prior = tuple(law.prefix_mass((), h) / law.total for h in range(law.private_symbols))
    best = Q(0)
    for g in law.public_paths():
        tv = sum(max(law.conditional(g, h) - prior[h], Q(0)) for h in range(law.private_symbols))
        best = max(best, tv)
    return 1 + best


def martingale_from_terminal(law: PrivateSignalLaw, terminal: dict) -> dict:
    """M_t = E[M_n | G_t] for a terminal value M_n given on public paths (public conditional expectation)."""
    paths = law.public_paths()
    if set(terminal) != set(paths) or any(_rational(terminal[g]) < 0 for g in paths):
        raise ValueError("terminal values must be given, nonnegative, on every positive-mass public path")
    out = {}
    for t in range(law.horizon + 1):
        for prefix in law.prefixes(t):
            den = law.prefix_mass(prefix)
            out[prefix] = sum(law.prefix_mass(g) * Q(terminal[g]) for g in paths if g[:t] == prefix) / den
    return out


def is_public_supermartingale(law: PrivateSignalLaw, process: dict) -> bool:
    """Checks M_t >= E[M_{t+1} | G_t] and M >= 0 on every positive-mass prefix."""
    for t in range(law.horizon):
        for prefix in law.prefixes(t):
            den = law.prefix_mass(prefix)
            nxt = sum(law.prefix_mass(c) * process[c] for c in law.children(prefix)) / den
            if process[prefix] < 0 or process[prefix] < nxt:
                return False
    return all(process[g] >= 0 for g in law.public_paths())


def worst_stopped_expectation(law: PrivateSignalLaw, process: dict):
    """Exact sup over F-stopping times tau of E[M_tau] for a public process M (dict prefix -> value).

    Decomposes tau = tau_h on {H = h}, each tau_h a public stopping time, and solves one
    optimal stopping problem per private symbol by backward induction on the public tree.
    Returns the value, the per-symbol values and the per-symbol stopping sets.
    """
    per_symbol = {}
    rules = {}
    for h in range(law.private_symbols):
        stop_set = set()

        def solve(prefix):
            den = law.prefix_mass(prefix)
            here = process[prefix] * law.prefix_mass(prefix, h)   # E[M_t 1{H=h}; prefix] unnormalised
            if len(prefix) == law.horizon:
                stop_set.add(prefix)
                return here
            cont = sum(solve(c) for c in law.children(prefix))
            if here >= cont:
                stop_set.add(prefix)
                return here
            return cont

        per_symbol[h] = solve(()) / law.total
        rules[h] = frozenset(stop_set)
    return {"value": sum(per_symbol.values()), "per_symbol": per_symbol, "stop_sets": rules}


def enumerate_private_stopping_times(law: PrivateSignalLaw, process: dict) -> Q:
    """Independent brute force: every F-stopping time as a stop/continue table on (prefix, h).

    Exponential; intended for tiny laws only.
    """
    nodes = [(p, h) for t in range(law.horizon) for p in law.prefixes(t)
             for h in range(law.private_symbols)]
    if len(nodes) > 18:
        raise ValueError("brute force restricted to at most 18 decision nodes")
    best = Q(0)
    for bits in product((0, 1), repeat=len(nodes)):
        stops = {node for node, b in zip(nodes, bits) if b}
        value = Q(0)
        for (g, h), m in law.mass.items():
            for t in range(law.horizon + 1):
                if t == law.horizon or (g[:t], h) in stops:
                    value += m * process[g[:t]]
                    break
        best = max(best, value)
    return best / law.total


def sequential_private_value(law: PrivateSignalLaw, process: dict, arrival: tuple[int, ...]) -> Q:
    """Private symbol h decoded gradually: coordinate j of h's digit expansion arrives at time arrival[j].

    The private symbol is written in mixed radix given by ``arrival``'s length (binary digits);
    here we take h's binary digits, least significant first, digit j revealed at time arrival[j]
    (a digit with arrival 0 is known from the start; arrival n+1 never arrives). The actor's
    filtration is F_t = G_t v sigma(digits arrived by t). Exact value by backward induction over
    (prefix, revealed digits).
    """
    digits = len(arrival)
    if (1 << digits) < law.private_symbols:
        raise ValueError("not enough digits to encode the private alphabet")
    if any(type(a) is not int or a < 0 for a in arrival):
        raise ValueError("arrival times must be nonnegative integers")

    def revealed(h, t):
        return tuple((h >> j) & 1 if arrival[j] <= t else None for j in range(digits))

    @lru_cache(None)
    def solve(prefix, known):
        t = len(prefix)
        # unnormalised mass of this information cell
        cell = [(hh, m) for (g, hh), m in law.mass.items()
                if g[:t] == prefix and revealed(hh, t) == known]
        here = process[prefix] * sum(m for _, m in cell)
        if t == law.horizon:
            return here
        cont = Q(0)
        for child in law.children(prefix):
            for nxt in {revealed(hh, t + 1) for hh, _ in cell}:
                cont += solve(child, nxt)
        return max(here, cont)

    total = Q(0)
    for known in {revealed(hh, 0) for (_, hh) in law.mass}:
        total += solve((), known)
    return total / law.total


def peek_law(accuracy, n_steps: int = 1) -> PrivateSignalLaw:
    """PR #8 Section 4 law: X fair bit revealed at time 1; private H equals X with probability p."""
    p = _rational(accuracy)
    if not 0 <= p <= 1 or n_steps != 1:
        raise ValueError("accuracy must be a probability; one step")
    mass = {}
    for x in (0, 1):
        for h in (0, 1):
            mass[((x,), h)] = Q(1, 2) * (p if h == x else 1 - p)
    return PrivateSignalLaw((2,), 2, mass)


def doubling_law(n: int) -> PrivateSignalLaw:
    """n fair bits; private H is the whole bit string (L = 2^n); M_t = 2^t prod 1{bits so far all one}."""
    if type(n) is not int or n < 1:
        raise ValueError("n must be a positive integer")
    mass = {}
    for bits in product((0, 1), repeat=n):
        h = sum(b << i for i, b in enumerate(bits))
        mass[(bits, h)] = Q(1, 2 ** n)
    return PrivateSignalLaw((2,) * n, 2 ** n, mass)


def doubling_process(n: int) -> dict:
    out = {}
    for t in range(n + 1):
        for prefix in product((0, 1), repeat=t):
            out[prefix] = Q(2 ** t) if all(prefix) else Q(0)
    return out


def rare_run_law(epsilon, n: int) -> PrivateSignalLaw:
    """n i.i.d. Bernoulli(epsilon) public bits; private H = number of leading successes (n + 1 symbols).

    With rare_run_process, the private stopper obtains n(1 - epsilon) + 1 for every epsilon. The
    information value V of the law is rare_run_value: 1 + (n - 1)(1 - epsilon) + max(1 - epsilon,
    epsilon), which equals n(1 - epsilon) + 1 only for epsilon <= 1/2 (for larger epsilon the path
    whose first failure is at the last step is the maximiser). Both approach the alphabet bound
    n + 1 as epsilon -> 0; the leakage certificate equals n + 1 for every epsilon.
    """
    e = _rational(epsilon)
    if not 0 < e < 1 or type(n) is not int or n < 1:
        raise ValueError("epsilon in (0, 1) and a positive horizon required")
    mass = {}
    for bits in product((0, 1), repeat=n):
        lead = 0
        while lead < n and bits[lead] == 1:
            lead += 1
        p = Q(1)
        for b in bits:
            p *= e if b else 1 - e
        mass[(bits, lead)] = p
    return PrivateSignalLaw((2,) * n, n + 1, mass)


def rare_run_value(epsilon, n: int) -> Q:
    """Closed form of private_stopping_value(rare_run_law(epsilon, n)): 1 + (n-1)(1-e) + max(1-e, e)."""
    e = _rational(epsilon)
    if not 0 < e < 1 or type(n) is not int or n < 1:
        raise ValueError("epsilon in (0, 1) and a positive horizon required")
    return 1 + (n - 1) * (1 - e) + max(1 - e, e)


def rare_run_process(epsilon, n: int) -> dict:
    """M_t = epsilon^{-t} prod_{s<=t} X_s: a nonnegative martingale with M_0 = 1."""
    e = _rational(epsilon)
    out = {}
    for t in range(n + 1):
        for prefix in product((0, 1), repeat=t):
            out[prefix] = e ** (-t) if all(prefix) else Q(0)
    return out


def rare_success_law(epsilon, n: int = 1) -> PrivateSignalLaw:
    """One Bernoulli(epsilon) public bit X, M_1 = X / epsilon, private H = X. Value 2 - epsilon."""
    e = _rational(epsilon)
    if not 0 < e <= 1:
        raise ValueError("epsilon must be in (0, 1]")
    return PrivateSignalLaw((2,), 2, {((1,), 1): e, ((0,), 0): 1 - e})


