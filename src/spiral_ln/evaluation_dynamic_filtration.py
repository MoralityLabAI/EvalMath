@dataclass(frozen=True)
class SourceModel:
    """Composite null: prior over omega; source i yields y ~ kernels[i][omega][y] independently given omega;
    factor i is factors[i][y] with sum_y factors[i][y] kernels[i][omega][y] <= 1 for every omega."""
    prior: tuple
    kernels: tuple
    factors: tuple

    def __post_init__(self):
        prior = _distribution(self.prior)
        kernels = []
        for k in self.kernels:
            rows = tuple(_distribution(r) for r in k)
            if len(rows) != len(prior) or any(len(r) != len(rows[0]) for r in rows):
                raise ValueError("each source kernel needs one row per world with a fixed alphabet")
            kernels.append(rows)
        factors = tuple(tuple(_rational(x) for x in f) for f in self.factors)
        if len(factors) != len(kernels) or any(len(f) != len(k[0]) for f, k in zip(factors, kernels)):
            raise ValueError("one factor row per source, matching the alphabet")
        for f, k in zip(factors, kernels):
            if any(x < 0 for x in f):
                raise ValueError("factors must be nonnegative")
            for row in k:
                if sum(x * p for x, p in zip(f, row)) > 1:
                    raise ValueError("factors must be pointwise valid: mean at most one in every world")
        object.__setattr__(self, "prior", prior)
        object.__setattr__(self, "kernels", tuple(kernels))
        object.__setattr__(self, "factors", factors)

    @property
    def sources(self):
        return len(self.kernels)


def _check_chronology(model: SourceModel, chronology):
    seen_view, seen_rev = set(), set()
    for ev, i in chronology:
        if ev not in ("VIEW", "REVOKE") or type(i) is not int or not 0 <= i < model.sources:
            raise ValueError("chronology events are ('VIEW', i) or ('REVOKE', i)")
        if ev == "VIEW":
            if i in seen_view:
                raise ValueError("each source is viewed at most once")
            seen_view.add(i)
        else:
            if i in seen_rev:
                raise ValueError("each source has at most one revocation slot")
            seen_rev.add(i)


def chronology_safe(model: SourceModel, chronology) -> bool:
    """True when every REVOKE slot precedes its own source's VIEW."""
    _check_chronology(model, chronology)
    events = list(chronology)
    for i in range(model.sources):
        if ("REVOKE", i) in events and ("VIEW", i) in events:
            if events.index(("REVOKE", i)) > events.index(("VIEW", i)):
                return False
    return True


def chronology_worst_case(model: SourceModel, chronology):
    """sup over revocation policies measurable in the certified filtration of E[prod_{i kept, viewed} F_i].

    A policy decides at each REVOKE slot as a function of the values viewed so far.
    Returns the value and an optimal policy as {(slot index, seen values): revoke?}.
    """
    _check_chronology(model, chronology)
    S = len(model.prior)
    policy = {}

    def rec(idx, mu, seen, revoked):
        if idx == len(chronology):
            e = Q(1)
            for j, y in seen:
                if j not in revoked:
                    e *= model.factors[j][y]
            return sum(mu) * e
        ev, i = chronology[idx]
        if ev == "VIEW":
            total = Q(0)
            for y in range(len(model.kernels[i][0])):
                mu2 = tuple(mu[s] * model.kernels[i][s][y] for s in range(S))
                if any(mu2):
                    total += rec(idx + 1, mu2, seen + ((i, y),), revoked)
            return total
        keep = rec(idx + 1, mu, seen, revoked)
        revoke = rec(idx + 1, mu, seen, revoked | frozenset([i]))
        policy[(idx, seen)] = revoke > keep
        return max(keep, revoke)

    value = rec(0, model.prior, (), frozenset())
    return {"value": value, "policy": policy}


def revocation_policy_value(model: SourceModel, chronology, decide) -> Q:
    """E[prod kept F] for an explicit policy decide(slot index, seen values) -> bool."""
    _check_chronology(model, chronology)
    S = len(model.prior)

    def rec(idx, mu, seen, revoked):
        if idx == len(chronology):
            e = Q(1)
            for j, y in seen:
                if j not in revoked:
                    e *= model.factors[j][y]
            return sum(mu) * e
        ev, i = chronology[idx]
        if ev == "VIEW":
            return sum(rec(idx + 1, tuple(mu[s] * model.kernels[i][s][y] for s in range(S)),
                           seen + ((i, y),), revoked)
                       for y in range(len(model.kernels[i][0])))
        if decide(idx, seen):
            revoked = revoked | frozenset([i])
        return rec(idx + 1, mu, seen, revoked)

    return rec(0, model.prior, (), frozenset())


def fair_bit_sources(count: int) -> SourceModel:
    """`count` fair bits under a point null; factor 2 on a one, 0 on a zero (a mean-one factor)."""
    if type(count) is not int or count < 1:
        raise ValueError("count must be a positive integer")
    return SourceModel((Q(1),), tuple(((Q(1, 2), Q(1, 2)),) for _ in range(count)),
                       tuple((Q(0), Q(2)) for _ in range(count)))


def single_source_after_view_value(model: SourceModel, source: int = 0) -> Q:
    """E[max(F, 1)] for one source viewed then revocable: the closed form of the one-slot inflation."""
    S = len(model.prior)
    return sum(model.prior[s] * model.kernels[source][s][y] * max(model.factors[source][y], Q(1))
               for s in range(S) for y in range(len(model.kernels[source][0])))


