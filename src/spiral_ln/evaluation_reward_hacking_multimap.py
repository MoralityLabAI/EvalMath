"""RHT-06: higher-dimensional, capacity-aware reward-feedback topology.

For k category maps observed on a declared set of joint marginals Delta, the
feedback channel is an integer incidence matrix M_Delta with one column per
nonempty joint cell. The rational nullspace can contain directions with
coefficients too large for any physically feasible integer count record.

The EXACT finite ambiguity object is the bounded integer kernel:
    B_s={z in Z^P : Mz=0 and -s_e <= z_e <= s_e}.
Every z in B_s is realized by two admissible count tables z_+, z_-
with the same feedback. For a frozen reachable roster X, use the smaller
difference space generated by x-x' for x,x' in X and Mx=Mx'.

All enumerations are capped. The coefficient groups for UGC constraint
holonomy and rational gold utility are distinct; no homology equivalence
is claimed for 3+ maps observed separately.
"""
from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction as Q
from itertools import combinations, product
from math import gcd, lcm

from spiral_ln.evaluation_leak_topology import (
    margin_rows_k, nullspace, rank,
)


@dataclass(frozen=True)
class MultiMapSignals:
    cells: tuple[tuple[int, ...], ...]
    capacities: tuple[int, ...]
    observed_faces: tuple[tuple[int, ...], ...]

    def __post_init__(self):
        cells=self.cells
        if (not cells or len(set(cells))!=len(cells)
            or tuple(sorted(cells))!=cells
            or len(self.capacities)!=len(cells)
            or any(type(s) is not int or s<1 for s in self.capacities)):
            raise ValueError("sorted distinct cells with positive integer capacities required")
        k=len(cells[0])
        if k<2 or any(len(c)!=k or any(type(u) is not int or u<0 for u in c)
                      for c in cells):
            raise ValueError("cells must have the same number of valid category coordinates")
        faces=self.observed_faces
        if (not faces or len(set(faces))!=len(faces)
            or any(len(face)!=len(set(face)) or not face
                   or tuple(sorted(face))!=face
                   or any(type(j) is not int or not 0<=j<k for j in face)
                   for face in faces)):
            raise ValueError("nonempty distinct ordered observation faces required")

    @property
    def matrix(self) -> tuple[tuple[int, ...], ...]:
        return tuple(tuple(v for v in row)
                     for row in margin_rows_k(self.cells,self.observed_faces))

    @property
    def rational_nullity(self) -> int:
        return len(self.cells)-rank(self.matrix)

    def feedback(self, x: tuple[int, ...]) -> tuple[int, ...]:
        if len(x)!=len(self.cells):
            raise ValueError("one count per cell required")
        return tuple(sum(a*v for a,v in zip(row,x)) for row in self.matrix)


def _gold(space: MultiMapSignals, gold_weights) -> tuple[Q, ...]:
    t=tuple(Q(v) for v in gold_weights)
    if len(t)!=len(space.cells):
        raise ValueError("one protected gold weight per cell required")
    return t


def primitive_integer_kernel_generators(
    space: MultiMapSignals,
) -> tuple[tuple[int, ...], ...]:
    """Primitive integer rescaling of a Q nullspace basis.

    The resulting vectors span ker_Q M, although they need not generate
    the entire integer lattice ker_Z M. No Markov-basis claim is made.
    """
    out=[]
    for v in nullspace(space.matrix,len(space.cells)):
        denom=lcm(*(x.denominator for x in v))
        raw=tuple(int(x*denom) for x in v)
        common=gcd(*(abs(u) for u in raw))
        z=tuple(u//common for u in raw)
        if next(v for v in z if v)!=1 and next(v for v in z if v)!=-1:
            pass
        # Choose positive leading nonzero coordinate for a fixed sign.
        if next(u for u in z if u)<0:
            z=tuple(-u for u in z)
        if any(space.feedback(z)):
            raise AssertionError("primitive vector must be in the feedback kernel")
        out.append(z)
    return tuple(out)


def bounded_kernel_differences(
    space: MultiMapSignals, *, max_vectors:int=150000
) -> tuple[tuple[int,...], ...]:
    """All realizable integer differences z in ker_Z(M) cap [-s,s]."""
    if type(max_vectors) is not int or max_vectors<1:
        raise ValueError("positive search budget required")
    budget=1
    for s in space.capacities:
        budget*=2*s+1
        if budget>max_vectors:
            raise ValueError("integer kernel census exceeds registered search budget")
    M=space.matrix
    vectors=[]
    for z in product(*(range(-s,s+1) for s in space.capacities)):
        if all(sum(a*v for a,v in zip(row,z))==0 for row in M):
            vectors.append(z)
    return tuple(vectors)


def bounded_kernel_rank(
    space: MultiMapSignals, *, max_vectors:int=150000
) -> int:
    return rank(bounded_kernel_differences(space,max_vectors=max_vectors))


def gold_alias_report(
    space: MultiMapSignals, gold_weights, *, max_vectors:int=150000
) -> dict:
    """Exact maximal hidden true-gold width and two feasible count tables."""
    t=_gold(space,gold_weights)
    kernel=bounded_kernel_differences(space,max_vectors=max_vectors)
    z=max(kernel,key=lambda a:sum((x*y for x,y in zip(t,a)),Q(0)))
    width=sum((x*y for x,y in zip(t,z)),Q(0))
    xhi=tuple(max(0,v) for v in z)
    xlo=tuple(max(0,-v) for v in z)
    assert width>=0 and space.feedback(xhi)==space.feedback(xlo)
    rational_basis=primitive_integer_kernel_generators(space)
    periods=tuple(sum((t_i*zi for t_i,zi in zip(t,v)),Q(0))
                  for v in rational_basis)
    return {
        "rational_nullity":space.rational_nullity,
        "bounded_integer_rank":rank(kernel),
        "rational_gold_observable":all(p==0 for p in periods),
        "bounded_gold_observable":width==0,
        "rational_periods":periods,
        "maximum_hidden_gold_width":width,
        "difference":z,
        "high_record":xhi,
        "low_record":xlo,
        "feedback":space.feedback(xhi),
        "number_bounded_differences":len(kernel),
    }


def minimum_private_audit(
    space: MultiMapSignals, gold_weights, *,
    tolerance:Q=Q(0),max_vectors:int=150000
) -> dict:
    """Fewest additional cell reads to bound gold ambiguity by tolerance."""
    t=_gold(space,gold_weights)
    epsilon=Q(tolerance)
    if epsilon<0:
        raise ValueError("negative gold ambiguity tolerance")
    kernel=bounded_kernel_differences(space,max_vectors=max_vectors)
    values=tuple((z,sum((w*v for w,v in zip(t,z)),Q(0)))
                 for z in kernel)
    m=len(t)
    for k in range(m+1):
        for S in combinations(range(m),k):
            remaining=max((value for z,value in values
                           if all(z[i]==0 for i in S)),default=Q(0))
            if remaining<=epsilon:
                return {
                    "audited_cells":S,
                    "count":len(S),
                    "remaining_width":remaining,
                    "epsilon":epsilon,
                }
    raise AssertionError("complete private audit always identifies true gold")


def reachable_gold_alias(
    space: MultiMapSignals, gold_weights, reachable_records,
    *, max_records:int=512
) -> dict:
    """Exact actor-reachable hidden-gold width under the same public channel.

    An environment's game/constraint map may exclude most possible cell
    tables, so the rational kernel and capacity-box kernel overstate the
    amount of hacking reachable by a particular controller roster.
    """
    t=_gold(space,gold_weights)
    X=tuple(tuple(x) for x in reachable_records)
    if (not X or len(X)>max_records or len(set(X))!=len(X)):
        raise ValueError("reachable records must be distinct, nonempty and capped")
    if any(len(x)!=len(t) or any(type(v) is not int or not 0<=v<=s
           for v,s in zip(x,space.capacities)) for x in X):
        raise ValueError("reachable records must satisfy cell capacities")
    by_feedback={}
    for x in X:
        y=space.feedback(x)
        by_feedback.setdefault(y,[]).append(x)
    differences=[]
    best=Q(0)
    witness=(X[0],X[0])
    for fibre in by_feedback.values():
        for hi in fibre:
            for lo in fibre:
                z=tuple(a-b for a,b in zip(hi,lo))
                differences.append(z)
                value=sum((a*b for a,b in zip(t,z)),Q(0))
                if value>best:
                    best=value
                    witness=(hi,lo)
    return {
        "reachable_records":len(X),
        "reachable_fibres":len(by_feedback),
        "reachable_difference_rank":rank(differences),
        "reachable_gold_observable":best==0,
        "maximum_hidden_gold_width":best,
        "high_record":witness[0],
        "low_record":witness[1],
    }


def first_uniform_capacity_alias(
    space:MultiMapSignals, gold_weights, *,
    max_capacity:int=5,max_vectors:int=150000
) -> dict | None:
    """Smallest uniform capacity at which the declared gold becomes ambiguous."""
    if type(max_capacity)is not int or max_capacity<1:
        raise ValueError("positive capacity search horizon required")
    for cap in range(1,max_capacity+1):
        candidate=MultiMapSignals(space.cells,(cap,)*len(space.cells),
                                  space.observed_faces)
        report=gold_alias_report(candidate,gold_weights,max_vectors=max_vectors)
        if not report["bounded_gold_observable"]:
            return {"uniform_capacity":cap,"witness":report}
    return None
